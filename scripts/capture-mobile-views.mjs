import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const out = 'eval/mobile-audit'; mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' }); await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/home-top.png` });
await page.click('#nav-toggle'); await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/home-menu.png` });
await page.click('#nav-sheet a[href="#try"]'); await page.waitForTimeout(3500);
await page.screenshot({ path: `${out}/try-top.png` });
await page.evaluate(() => document.getElementById('atlas').scrollIntoView({ behavior: 'instant' })); await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/try-atlas.png` });
await page.click('#gs-list .gs-item'); await page.waitForTimeout(2000);
await page.screenshot({ path: `${out}/try-dept.png` });
await page.click('#graph-focus-head .gfh-wf'); await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/try-workflow.png` });
await page.click('#pmap .p-node[data-step="1"]'); await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/try-inspector.png` });
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
await page.goto('http://localhost:5173/#platform', { waitUntil: 'networkidle' }); await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/platform-top.png` });
await page.goto('http://localhost:5173/#about', { waitUntil: 'networkidle' }); await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/about-top.png` });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
console.log(overflow ? 'HORIZONTAL OVERFLOW' : 'no overflow', errors.length ? errors : 'no page errors');
await browser.close();
